    document.getElementById("tiempoFinal");


// ==================================================
// MEZCLAR
// ==================================================

function mezclar(array) {

    let copia = [...array];

    for (let i = copia.length - 1; i > 0; i--) {

        let posicion =
            Math.floor(Math.random() * (i + 1));

        let temporal =
            copia[i];

        copia[i] =
            copia[posicion];

        copia[posicion] =
            temporal;
    }

    return copia;
}


// ==================================================
// INICIAR TEST
// ==================================================

function iniciarTest(aleatorio) {

    preguntaActual = 0;

    puntos = 0;

    tiempo = 0;

    clearInterval(intervalo);


    if (aleatorio) {

        preguntasTest =
            mezclar(preguntas);

    } else {

        preguntasTest =
            [...preguntas];

    }


    seleccionModo.classList.add("oculto");

    resultado.classList.add("oculto");

    test.classList.remove("oculto");


    puntuacion.textContent =
        "Puntos: 0";


    contador.textContent =
        "⏱️ 00:00";


    intervalo = setInterval(
        function () {

            tiempo++;

            actualizarContador();

        },
        1000
    );


    mostrarPregunta();
}


// ==================================================
// ACTUALIZAR CONTADOR
// ==================================================

function actualizarContador() {

    let minutos =
        Math.floor(tiempo / 60);

    let segundos =
        tiempo % 60;


    let minutosTexto =
        minutos.toString().padStart(2, "0");

    let segundosTexto =
        segundos.toString().padStart(2, "0");


    contador.textContent =
        `⏱️ ${minutosTexto}:${segundosTexto}`;
}


// ==================================================
// MOSTRAR PREGUNTA
// ==================================================

function mostrarPregunta() {

    respuestaSeleccionada = false;

    botonSiguiente.disabled = true;


    let preguntaActualObjeto =
        preguntasTest[preguntaActual];


    numeroPregunta.textContent =
        `Pregunta ${preguntaActual + 1} de ${preguntasTest.length}`;


    pregunta.textContent =
        preguntaActualObjeto.pregunta;


    opciones.innerHTML = "";


    let respuestas =
        preguntaActualObjeto.opciones.map(
            function (texto, indice) {

                return {

                    texto: texto,

                    correcta:
                        indice ===
                        preguntaActualObjeto.correcta

                };

            }
        );


    // Mezclar las respuestas

    respuestas =
        mezclar(respuestas);


    respuestas.forEach(
        function (respuesta) {

            const boton =
                document.createElement("button");


            boton.classList.add("opcion");


            boton.textContent =
                respuesta.texto;


            boton.addEventListener(
                "click",
                function () {

                    seleccionarRespuesta(
                        respuesta.correcta,
                        boton
                    );

                }
            );


            opciones.appendChild(boton);

        }
    );


    let progreso =
        (
            (preguntaActual + 1)
            / preguntasTest.length
        ) * 100;


    barraProgreso.style.width =
        progreso + "%";
}


// ==================================================
// SELECCIONAR RESPUESTA
// ==================================================

function seleccionarRespuesta(
    esCorrecta,
    botonSeleccionado
) {

    if (respuestaSeleccionada) {

        return;

    }


    respuestaSeleccionada = true;


    let preguntaActualObjeto =
        preguntasTest[preguntaActual];


    let respuestaCorrecta =
        preguntaActualObjeto.opciones[
            preguntaActualObjeto.correcta
        ];


    const botones =
        document.querySelectorAll(".opcion");


    botones.forEach(
        function (boton) {

            if (
                boton.textContent ===
                respuestaCorrecta
            ) {

                boton.classList.add(
                    "correcta"
                );

            }

        }
    );


    if (esCorrecta) {

        puntos++;


        puntuacion.textContent =
            `Puntos: ${puntos}`;

    } else {

        botonSeleccionado.classList.add(
            "incorrecta"
        );

    }


    botonSiguiente.disabled =
        false;
}


// ==================================================
// SIGUIENTE PREGUNTA
// ==================================================

botonSiguiente.addEventListener(
    "click",
    function () {

        preguntaActual++;


        if (
            preguntaActual <
            preguntasTest.length
        ) {

            mostrarPregunta();

        } else {

            mostrarResultado();

        }

    }
);


// ==================================================
// MOSTRAR RESULTADO
// ==================================================

function mostrarResultado() {

    clearInterval(intervalo);


    test.classList.add("oculto");

    resultado.classList.remove("oculto");


    let notaFinal =
        (puntos / preguntasTest.length) * 10;


    nota.textContent =
        notaFinal.toFixed(2) + "/10";


    mensajeResultado.textContent =
        `Has acertado ${puntos} de ${preguntasTest.length} preguntas.`;


    let minutos =
        Math.floor(tiempo / 60);

    let segundos =
        tiempo % 60;


    let minutosTexto =
        minutos.toString().padStart(2, "0");

    let segundosTexto =
        segundos.toString().padStart(2, "0");


    tiempoFinal.textContent =
        `⏱️ Tiempo empleado: ${minutosTexto}:${segundosTexto}`;
}


// ==================================================
// VOLVER A ELEGIR MODO
